"""Run after replacing the orchid films. Requires ffprobe on PATH."""

from base64 import b64encode
from fractions import Fraction
import json
from pathlib import Path
import subprocess

ORCHID = Path(__file__).resolve().parents[1] / 'public' / 'orchid'


def index(filename, stream):
    fields = 'stream=codec_name,width,height,level,r_frame_rate,time_base,extradata:packet=pts,size,pos,flags'
    probe = subprocess.check_output([
        'ffprobe', '-v', 'error', '-select_streams', stream, '-show_entries', fields,
        '-show_data', '-of', 'json', str(ORCHID / filename),
    ])
    result = json.loads(probe)
    track = result['streams'][0]
    packets = result['packets']
    rate = Fraction(track['r_frame_rate'])
    timebase = Fraction(track['time_base'])
    order = [int(packet['pts']) * timebase * rate for packet in packets]
    if rate.denominator != 1 or sorted(order) != list(range(len(packets))):
        raise ValueError(f'{filename}: expected a constant-rate loop starting at zero')
    if any(int(a['pos']) + int(a['size']) != int(b['pos']) for a, b in zip(packets, packets[1:])):
        raise ValueError(f'{filename}: these video samples are not contiguous')
    description = bytes.fromhex(' '.join(
        line.split(': ')[1].split('  ')[0] for line in track['extradata'].splitlines() if line
    ))
    info = {'file': filename, 'width': track['width'], 'height': track['height'],
            'fps': int(rate), 'offset': int(packets[0]['pos']),
            'sizes': [int(p['size']) for p in packets],
            'keys': [i for i, p in enumerate(packets) if 'K' in p['flags']]}
    if track['codec_name'] == 'av1':
        # The shipped AVIF sequences use AV1 Main profile, Main tier, 8-bit samples.
        info['codec'] = f'av01.0.{track["level"]:02d}M.08'
    elif track['codec_name'] == 'hevc':
        # RFC 6381 HEVC codec suffix from the hvcC decoder configuration record.
        profile = description[1]
        space = ['', 'A', 'B', 'C'][profile >> 6]
        flags = int.from_bytes(description[2:6], 'big')
        compatibility = int(f'{flags:032b}'[::-1], 2)
        tier = 'H' if profile & 32 else 'L'
        constraints = ''.join(f'.{byte:02X}' for byte in description[6:12].rstrip(b'\x00'))
        info['codec'] = f'hvc1.{space}{profile & 31}.{compatibility:X}.{tier}{description[12]}{constraints}'
        info['description'] = b64encode(description).decode('ascii')
    elif track['codec_name'] == 'h264':
        info['codec'] = 'avc1.' + description[1:4].hex()
        info['description'] = b64encode(description).decode('ascii')
    else:
        raise ValueError(f'{filename}: unsupported codec')
    if order != list(range(len(packets))):
        info['order'] = [int(value) for value in order]
    return info


assets = [('mobile', 'wind-mobile.avif', 'v:1'), ('compact', 'wind-loop.avif', 'v:1'),
          ('hevc', 'wind-mobile.heics', 'v:1'), ('avc', 'wind-film.mp4', 'v:0')]
lines = ['// Generated by scripts/orchid-frame-index.py. The sample bytes stay in the media files.']
for name, filename, stream in assets:
    lines.append(f'export const {name} = {{')
    for key, value in index(filename, stream).items():
        if isinstance(value, list) and len(value) > 16:
            lines.append(f'  {key}: [')
            for start in range(0, len(value), 16):
                lines.append('    ' + ', '.join(map(str, value[start:start + 16])) + ',')
            lines.append('  ],')
        else:
            lines.append(f'  {key}: {json.dumps(value)},')
    lines.append('};\n')
(ORCHID / 'frame-index.js').write_text('\n'.join(lines))
